#!/usr/bin/env node
// Component integrity (EV-007 item 8, REQ-010).
//
//   node scripts/check-components.mjs            verify (exit 1 on any mismatch)
//   node scripts/check-components.mjs --update   rewrite components.lock.json from disk
//
// Run --update only right after the shadcn CLI installs or updates a component, in the
// same commit. Never hand-edit files under the component directories.
//
// What this proves: any change to a generated component file arrives with a matching lock
// change in the same diff, and every required component is present. It does not compare
// files against the registry; provenance comes from running the CLI.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const UI_DIR = "src/web/components/ui";
const AI_DIR = "src/web/components/ai-elements";
const LOCK = join(root, "components.lock.json");
// The single source of truth for which components JM-001 requires, keyed by install dir.
const REQUIRED = {
  [AI_DIR]: ["conversation", "message", "prompt-input", "suggestion", "task", "inline-citation", "sources", "shimmer"],
  [UI_DIR]: ["table", "badge", "select", "alert-dialog", "alert"],
};

const sha256 = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
const walk = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)],
      )
    : [];
const onDisk = () =>
  Object.fromEntries(
    [UI_DIR, AI_DIR]
      .flatMap((d) => walk(join(root, d)))
      .map((p) => relative(root, p).split("\\").join("/"))
      .sort()
      .map((p) => [p, sha256(join(root, p))]),
  );

if (process.argv.includes("--update")) {
  const lock = {
    note: "SHA-256 of each file as written by the shadcn CLI. Generated by scripts/check-components.mjs --update.",
    files: onDisk(),
  };
  writeFileSync(LOCK, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(`components.lock.json updated: ${Object.keys(lock.files).length} files`);
  process.exit(0);
}

const errors = [];
const cfg = JSON.parse(readFileSync(join(root, "components.json"), "utf8"));
if (!cfg.registries?.["@ai-elements"]?.includes("registry.ai-sdk.dev")) errors.push("components.json does not list the @ai-elements registry");
if (cfg.aliases?.hooks !== "@/web/lib/hooks") errors.push(`components.json aliases.hooks is ${cfg.aliases?.hooks}, expected @/web/lib/hooks`);

if (!existsSync(LOCK)) errors.push("components.lock.json is missing");
else {
  const lock = JSON.parse(readFileSync(LOCK, "utf8"));
  const locked = lock.files ?? {};
  const disk = onDisk();
  for (const [p, h] of Object.entries(locked)) {
    if (!(p in disk)) errors.push(`missing: ${p}`);
    else if (disk[p] !== h) errors.push(`modified: ${p} (expected ${h}, found ${disk[p]})`);
  }
  for (const p of Object.keys(disk)) if (!(p in locked)) errors.push(`not in lock: ${p}`);
  for (const [dir, names] of Object.entries(REQUIRED)) {
    for (const n of names) if (!(`${dir}/${n}.tsx` in locked)) errors.push(`required component not locked: ${dir}/${n}`);
  }
}

if (errors.length) {
  console.error(`COMPONENTS FAILED:\n${errors.map((e) => `  ${e}`).join("\n")}`);
  process.exit(1);
}
console.log(`COMPONENTS OK: ${Object.keys(onDisk()).length} files match components.lock.json`);
